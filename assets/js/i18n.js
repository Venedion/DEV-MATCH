  let language = 'en';
  try {
    language = localStorage.getItem(storageKey) === 'id' ? 'id' : 'en';
  } catch (error) {
    console.error('Unable to read interface language preference.', error);
  }

  function translateValue(value) {
    const trimmed = value.trim();
    if (!trimmed) return value;
    const countMatch = language === 'id'
      ? trimmed.match(/^(\d+) (projects|saved|clients|results)$/)
      : trimmed.match(/^(\d+) (proyek|tersimpan|klien|hasil)$/);
    if (countMatch) {
      const countLabels = language === 'id'
        ? { projects: 'proyek', saved: 'tersimpan', clients: 'klien', results: 'hasil' }
        : { proyek: 'projects', tersimpan: 'saved', klien: 'clients', hasil: 'results' };
      return `${value.slice(0, value.indexOf(trimmed))}${countMatch[1]} ${countLabels[countMatch[2]]}${value.slice(value.indexOf(trimmed) + trimmed.length)}`;
    }
    const translated = language === 'id'
      ? translations[trimmed]
      : reverseTranslations.get(trimmed);
    if (!translated) return value;
    const start = value.indexOf(trimmed);
    return `${value.slice(0, start)}${translated}${value.slice(start + trimmed.length)}`;
  }

  function isProtected(node) {
    const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
    return Boolean(element && element.closest(protectedSelectors));
  }

  function translateElement(element) {
    if (isProtected(element)) return;
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    let textNode;
    while ((textNode = walker.nextNode())) {
      if (isProtected(textNode)) continue;
      const translated = translateValue(textNode.nodeValue);
      if (translated !== textNode.nodeValue) textNode.nodeValue = translated;
    }

    const attributeTargets = [
      ...(element.matches('[placeholder], [title], [aria-label]') ? [element] : []),
      ...element.querySelectorAll('[placeholder], [title], [aria-label]')
    ];
    attributeTargets.forEach(target => {
      if (isProtected(target)) return;
      ['placeholder', 'title', 'aria-label'].forEach(attribute => {
        const value = target.getAttribute(attribute);
        if (value) target.setAttribute(attribute, translateValue(value));
      });
    });
  }

  function setLanguage(nextLanguage) {
    const updatedLanguage = nextLanguage === 'id' ? 'id' : 'en';
    localStorage.setItem(storageKey, updatedLanguage);
    language = updatedLanguage;
    document.documentElement.lang = language;
    translateElement(document.body);
    if (document.title) document.title = translateValue(document.title);
    document.dispatchEvent(new CustomEvent('devmatch:languagechange', { detail: { language } }));
  }

  function initialize() {
    document.documentElement.lang = language;
    translateElement(document.body);
    if (document.title) document.title = translateValue(document.title);

    const observer = new MutationObserver(records => {
      records.forEach(record => {
        if (record.type === 'characterData') {
          if (!isProtected(record.target)) {
            const translated = translateValue(record.target.nodeValue);
            if (translated !== record.target.nodeValue) record.target.nodeValue = translated;
          }
          return;
        }
        record.addedNodes.forEach(node => {
          if (node.nodeType === Node.ELEMENT_NODE) translateElement(node);
          else if (node.nodeType === Node.TEXT_NODE && !isProtected(node)) {
            const translated = translateValue(node.nodeValue);
            if (translated !== node.nodeValue) node.nodeValue = translated;
          }
        });
      });
    });
    observer.observe(document.body, { childList: true, characterData: true, subtree: true });
  }

  window.devMatchI18n = {
    getLanguage: () => language,
    setLanguage
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initialize, { once: true });
  } else {
    initialize();
  }
